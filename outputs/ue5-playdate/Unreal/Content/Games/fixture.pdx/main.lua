local tone = assert(playdate.sound.sampleplayer.new("tone"))
tone:play(0)
local gfx = playdate.graphics
assert(playdate.file.mkdir("images"))
local file = assert(playdate.file.open("binary.dat", playdate.file.kFileWrite))
assert(file:write("A\0B\0C") == 5)
file:close()
assert(playdate.file.exists("binary.dat"))
file = assert(playdate.file.open("binary.dat", playdate.file.kFileRead))
assert(file:read(5) == "A\0B\0C")
file:close()
local image = gfx.image.new(8, 8, gfx.kColorBlack)
assert(playdate.datastore.writeImage(image, "images/test.pdi"))
assert(playdate.datastore.readImage("images/test")):draw(0, 0)
assert(playdate.graphics.image.new("images/test"))
local reload = assert(playdate.graphics.image.new(8,8))
assert(reload:load("images/test"))
function playdate.update()
 gfx.clear(gfx.kColorWhite)
 local mask = playdate.getButtonState()
 gfx.fillRect(10, 10, 50 + mask, 20)
 local radians = playdate.getCrankPosition() * math.pi / 180
 gfx.drawLine(200, 120, 200 + 70 * math.cos(radians), 120 + 70 * math.sin(radians))
end
