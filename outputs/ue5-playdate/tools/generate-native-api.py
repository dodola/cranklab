"""Generate 32-bit Playdate function-table layout from the installed SDK.

Only API structs made entirely of function/table pointers are accepted. An
unrecognized field stops generation rather than silently shifting the ABI.
"""
import argparse
import json
import re
from pathlib import Path


def generate(sdk, output):
    sources = [sdk / "C_API/pd_api.h", *sorted((sdk / "C_API/pd_api").glob("*.h"))]
    structs = {}
    for path in sources:
        text = path.read_text(encoding="utf-8-sig")
        text = re.sub(r"/\*.*?\*/|//[^\n]*", "", text, flags=re.S)
        for match in re.finditer(r"struct\s+(PlaydateAPI|playdate_\w+)\s*\{(.*?)\};", text, re.S):
            fields = []
            for field in match[2].split(";"):
                field = " ".join(field.split())
                if not field:
                    continue
                fn = re.fullmatch(r"(.+?)\s*\(\s*\*\s*(\w+)\s*\)\s*\((.*)\)", field)
                sub = re.fullmatch(r"(?:const\s+)?struct\s+(playdate_\w+)\s*\*\s*(\w+)", field)
                reserved = re.fullmatch(r"uintptr_t\s+reserved\[(\d+)\]", field)
                if fn:
                    fields.append(dict(name=fn[2], result=fn[1], args=fn[3]))
                elif sub:
                    fields.append(dict(name=sub[2], table=sub[1]))
                elif reserved:
                    fields += [dict(name=f"reserved_{i}", reserved=True) for i in range(int(reserved[1]))]
                else:
                    raise ValueError(f"Unrecognized API field in {match[1]}: {field}")
            structs[match[1]] = fields
    tables, functions, fields = [], [], []

    def walk(typename, prefix):
        index = len(tables)
        tables.append(dict(name=typename, path=prefix, count=len(structs[typename])))
        for slot, field in enumerate(structs[typename]):
            name = f"{prefix}.{field['name']}" if prefix else field["name"]
            if field.get("reserved"):
                fields.append((index, slot, -1, -1))
            elif "table" in field:
                child = walk(field["table"], name)
                fields.append((index, slot, child, -1))
            else:
                fid = len(functions)
                functions.append(dict(name=name, result=field["result"], args=field["args"]))
                fields.append((index, slot, -1, fid))
        return index

    walk("PlaydateAPI", "")
    lines = ["// Generated by tools/generate-native-api.py; all guest pointers are 32-bit.",
             "static const ApiTableDef native_tables[] = {"]
    lines += [f'    {{{json.dumps(t["path"])}, {t["count"]}}},' for t in tables]
    lines += ["};", "static const ApiFieldDef native_fields[] = {"]
    lines += [f"    {{{t}, {s}, {child}, {fid}}}," for t, s, child, fid in fields]
    lines += ["};", "static const ApiFunctionDef native_functions[] = {"]
    lines += ["    {" + ", ".join(json.dumps(f[k]) for k in ("name", "result", "args")) + "}," for f in functions]
    lines += ["};", ""]
    output.write_text("\n".join(lines), encoding="utf-8")
    output.with_suffix(".json").write_text(json.dumps(dict(tables=tables, functions=functions), indent=2), encoding="utf-8")
    print(f"Generated {len(tables)} tables / {len(functions)} functions: {output}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--sdk", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    generate(args.sdk, args.output)
