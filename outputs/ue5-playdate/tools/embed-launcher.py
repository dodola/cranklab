"""Generate the owned Lua adapter embedded in crank-core (no runtime eval env)."""
import json
from pathlib import Path
root=Path(__file__).resolve().parents[1]/'runtime'
source=(root/'launcher/pdgames.lua').read_text(encoding='utf-8')
lines=['/* Generated by tools/embed-launcher.py. Edit launcher/pdgames.lua. */',
       'static const char pd_launcher_script[] =']
lines += [json.dumps(line+'\n',ensure_ascii=True) for line in source.splitlines()]
lines += [';','']
target=root/'src/pd_launcher_script.inc'
target.write_text('\n'.join(lines),encoding='utf-8')
print(f'Embedded PDGames adapter: {len(source)} bytes')
